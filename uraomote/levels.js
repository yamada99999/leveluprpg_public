//                  ふつうに遊べば当たらないよう、通り道の「真逆側」に置く。
// draw: { maxLen } … 「相手の画面に床を描く」ギミックを使うステージ。
//
// 新しく作ったら：node tools/check-levels.js（配置チェック）と、全パターンのテストプレイをすること。

